    #[test]
    fn the_sudoers_file_names_each_forced_command_and_nothing_wider() {
        let r = read(&sample()).unwrap();
        let mut other = sample();
        other["tenant_id"] = json!("t-bbb");
        // a second member with the same scope and roles: one rule, not two
        other["members"][2]["roles"] = json!(["owner"]);
        other["members"][2]["scope"] = json!("tenant");
        let o = read(&other).unwrap();
        let file = sudoers_file(&[r.clone(), o]).unwrap();
        let lines: Vec<&str> = file.lines().collect();
        assert_eq!(lines[0], SUDOERS_HEADER);
        assert_eq!(lines[1], SUDOERS_DEFAULTS);
        assert_eq!(
            &lines[2..],
            [
                "cloudgate ALL=(root) NOPASSWD: /usr/local/sbin/aib-cloud-host customer --tenant t-aaa --roles owner",
                "cloudgate ALL=(root) NOPASSWD: /usr/local/sbin/aib-cloud-host customer --tenant t-aaa --sites site2\\,site3 --roles viewer\\,analyst",
                "cloudgate ALL=(root) NOPASSWD: /usr/local/sbin/aib-cloud-host customer --tenant t-aaa --sites site3 --roles editor\\,publisher\\,analyst",
                "cloudgate ALL=(root) NOPASSWD: /usr/local/sbin/aib-cloud-host customer --tenant t-bbb --roles owner",
                "cloudgate ALL=(root) NOPASSWD: /usr/local/sbin/aib-cloud-host customer --tenant t-bbb --sites site3 --roles editor\\,publisher\\,analyst",
            ]
        );
        // no wildcard, and every rule is exactly an entry line's command
        assert!(!file.contains('*'));
        for l in entry_lines(&r) {
            let cmd = l
                .split('"')
                .nth(1)
                .unwrap()
                .strip_prefix("sudo -n ")
                .unwrap();
            let rule = format!("cloudgate ALL=(root) NOPASSWD: {}", cmd.replace(',', "\\,"));
            assert!(lines.contains(&rule.as_str()), "{rule}");
        }
        // the constants agree with each other
        assert_eq!(ENTRY_COMMAND, format!("sudo -n {ENTRY_TARGET}"));
        assert_eq!(
            SUDOERS_RULE_HEAD,
            format!("{ENTRY_ACCOUNT} ALL=(root) NOPASSWD: {ENTRY_TARGET} ")
        );
        assert!(SUDOERS_DEFAULTS.starts_with(&format!("Defaults:{ENTRY_ACCOUNT} ")));
        // a member whose entry keys are all revoked has no rule
        let mut v = sample();
        v["members"][0]["keys"][0]["revoked"] = json!("2026-11-11T01:00:00Z");
        let file = sudoers_file(&[read(&v).unwrap()]).unwrap();
        assert!(!file.contains("--tenant t-aaa --roles owner"));
        // two rosters of one tenant: refused
        assert_eq!(
            sudoers_file(&[r.clone(), r]),
            Err(SudoersBad::DuplicateTenant)
        );
        // two tenants registering one address: refused (c477a, share gate M1)
        let mut a = sample();
        a["emails"] = json!(["owner@example.com"]);
        let mut b = sample();
        b["tenant_id"] = json!("t-bbb");
        b["emails"] = json!(["other@example.com", "OWNER@example.com"]);
        assert_eq!(
            sudoers_file(&[read(&a).unwrap(), read(&b).unwrap()]),
            Err(SudoersBad::EmailOnTwoTenants)
        );
        assert_eq!(
            SudoersBad::EmailOnTwoTenants.as_str(),
            "email_on_two_tenants"
        );
        // different addresses: the file is written
        let mut b2 = b;
        b2["emails"] = json!(["other@example.com"]);
        assert!(sudoers_file(&[read(&a).unwrap(), read(&b2).unwrap()]).is_ok());
        // no roster: the header and Defaults only, the account may run nothing
        assert_eq!(sudoers_file(&[]).unwrap().lines().count(), 2);
        assert_eq!(sudoers_escape("a\\b,c:d=e"), "a\\\\b\\,c\\:d\\=e");
    }

