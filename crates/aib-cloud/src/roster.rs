    #[test]
    fn the_registered_addresses_are_read_normalized_and_optional() {
        // absent: none registered (an old roster still reads)
        assert!(read(&sample()).unwrap().emails.is_empty());
        let mut v = sample();
        v["emails"] = json!([" Owner@Example.com", "staff@example.com"]);
        assert_eq!(
            read(&v).unwrap().emails,
            ["owner@example.com", "staff@example.com"]
        );
        let bad = |emails: Value| {
            let mut v = sample();
            v["emails"] = emails;
            read(&v).unwrap_err()
        };
        // one bad entry refuses the roster; nothing is skipped
        assert_eq!(bad(json!(["owner@example.com", "owner"])), Bad::Email);
        assert_eq!(bad(json!(["owner@example.com", 1])), Bad::Email);
        // the same address twice, once normalized
        assert_eq!(
            bad(json!(["owner@example.com", "OWNER@example.com "])),
            Bad::Email
        );
        assert_eq!(bad(json!("owner@example.com")), Bad::Shape);
        assert_eq!(Bad::Email.as_str(), "bad_email");
    }

    #[test]
    fn strict_reading() {
        assert_eq!(parse("{", SITES), Err(Bad::NotJson));
        assert_eq!(parse("[]", SITES), Err(Bad::Shape));
        let bad = |edit: &dyn Fn(&mut Value)| {
            let mut v = sample();
            edit(&mut v);
            read(&v).unwrap_err()
        };
        // a field nobody named, at each level
        assert_eq!(bad(&|v| v["client_id"] = json!("x")), Bad::UnknownField);
        assert_eq!(
            bad(&|v| v["members"][0]["shell"] = json!(true)),
            Bad::UnknownField
        );
        assert_eq!(
            bad(&|v| v["members"][0]["keys"][0]["options"] = json!("pty")),
            Bad::UnknownField
        );
        assert_eq!(bad(&|v| v["name"] = json!(1)), Bad::Shape);
        assert_eq!(bad(&|v| v["members"] = json!({})), Bad::Shape);
        assert_eq!(bad(&|v| v["members"][0]["keys"] = json!(null)), Bad::Shape);
        assert_eq!(
            bad(&|v| v["members"][0]["identity_id"] = json!("M 1")),
            Bad::Member
        );
        assert_eq!(
            bad(&|v| v["members"][1]["identity_id"] = json!("m-01")),
            Bad::Repeated
        );
        for roles in [
            json!([]),
            json!(["owner", "owner"]),
            json!(["root"]),
            json!("owner"),
        ] {
            assert_eq!(
                bad(&|v| v["members"][0]["roles"] = roles.clone()),
                Bad::Roles
            );
        }
        for scope in [
            json!("all"),
            json!([]),
            json!(["site3", "site3"]),
            json!(["../x"]),
            json!(null),
        ] {
            assert_eq!(
                bad(&|v| v["members"][1]["scope"] = scope.clone()),
                Bad::Scope,
                "{scope}"
            );
        }
        assert_eq!(
            bad(&|v| {
                v["members"][1].as_object_mut().unwrap().remove("scope");
            }),
            Bad::Scope
        );
        // a key is one ed25519 key and nothing around it
        for line in [
            format!("{} me@laptop", key(0)),
            format!("no-pty {}", key(0)),
            format!("{}\n{}", key(0), key(1)),
            key(0).replace("ssh-ed25519", "ssh-rsa"),
            key(0)[..70].to_string(),
            String::new(),
        ] {
            assert_eq!(
                bad(&|v| v["members"][0]["keys"][0]["public_key"] = json!(line.clone())),
                Bad::Key,
                "{line:?}"
            );
        }
        assert_eq!(
            bad(&|v| v["members"][1]["keys"][0]["public_key"] = json!(key(0))),
            Bad::Repeated
        );
        assert_eq!(
            bad(&|v| v["members"][0]["keys"][0]["use"] = json!("both")),
            Bad::Key
        );
        assert_eq!(
            bad(&|v| v["members"][0]["keys"][0]["added"] = json!("yesterday")),
            Bad::Key
        );
        assert_eq!(
            bad(&|v| {
                v["members"][0]["keys"][0]
                    .as_object_mut()
                    .unwrap()
                    .remove("added");
            }),
            Bad::Key
        );
        assert_eq!(
            bad(&|v| v["members"][0]["keys"][0]["revoked"] = json!(true)),
            Bad::Key
        );
        assert_eq!(
            bad(&|v| v["members"][0]["keys"][0]["fingerprint"] = json!("MD5:aa")),
            Bad::Key
        );
        let mut v = sample();
        v["members"][0]["keys"][0]["fingerprint"] = json!(format!(
            "SHA256:{}",
            core::iter::repeat_n('a', 43).collect::<String>()
        ));
        assert!(read(&v).is_ok());
        assert_eq!(Bad::TenantIsSiteCode.as_str(), "tenant_id_is_a_site_code");
    }
